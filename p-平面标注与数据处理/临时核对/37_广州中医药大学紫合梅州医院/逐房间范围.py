def rect(x0,y0,x1,y1):return [(x0,y0),(x1,y0),(x1,y1),(x0,y1)]
def room(bounds,door=None,target=None,name=None,typ='unknown',connected=False):
    return dict(polygon=rect(*bounds) if len(bounds)==4 and isinstance(bounds[0],(int,float)) else bounds,
                door=door,target=target,name=name,type=typ,connected=connected)
def group(sid,mode,label,rooms,extra=None):
    GROUPS.append(dict(parent=sid,mode=mode,label=label,rooms=rooms,extra=extra))

