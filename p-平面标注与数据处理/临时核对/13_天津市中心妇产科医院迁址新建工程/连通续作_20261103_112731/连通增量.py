def change(rid, a, b, why):
    r = rels[rid]
    audit.append({'action': 'correct', 'id': rid, 'before': deepcopy(r), 'why': why})
    r['source'], r['target'] = a, b

def add(a, b, why):
    matches = [r for r in rels.values() if r['type'] == 'access' and {r['source'], r['target']} == {a, b}]
    if matches:
        return matches[0]['id']
    n = max(int(k[1:]) for k in rels if k.startswith('R')) + 1
    rid = f'R{n:03d}'
    rels[rid] = {'id': rid, 'source': a, 'target': b, 'type': 'access'}
    audit.append({'action': 'add', 'id': rid, 'source': a, 'target': b, 'why': why})
    return rid

def point(rid, x, y, kind='door'):
    rels[rid].setdefault('openings', []).append({'kind': kind, 'position_px': [x, y]})

