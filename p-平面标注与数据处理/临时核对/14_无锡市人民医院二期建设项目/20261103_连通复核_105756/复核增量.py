def pair(a, b):
    return frozenset((a, b))

def access(a, b, reason):
    for r in data['relations']:
        if r['type'] == 'access' and pair(r['source'], r['target']) == pair(a, b):
            return r['id']
    rid = f'R{max(int(r["id"][1:]) for r in data["relations"] if r["id"].startswith("R")) + 1:03}'
    r = {'id': rid, 'source': a, 'target': b, 'type': 'access'}
    data['relations'].append(r)
    byid[rid] = r
    new_relations.append({'id': rid, 'source': a, 'target': b, 'reason': reason})
    return rid

