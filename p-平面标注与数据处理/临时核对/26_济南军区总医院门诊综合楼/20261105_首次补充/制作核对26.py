def numbered_crop(box,ids,path,use_review=False):
    x0,y0,x1,y1=box;scale=2
    crop=im.crop(box).resize(((x1-x0)*scale,(y1-y0)*scale))
    draw=ImageDraw.Draw(crop)
    for sid in ids:
        s=ss[sid];poly=Polygon(s['polygon_px']);col='#a4144c'
        pts=[((x-x0)*scale,(y-y0)*scale) for x,y in s['polygon_px']]
        draw.line(pts+[pts[0]],fill=col,width=3)
        if use_review:
            x,y,_=badge[sid];lab=mp[sid]['review_id']
        else:
            # Put the badge by an interior corner, away from the center room name.
            visible=poly.intersection(geom_box(*box))
            a,b,cx,e=visible.bounds;y=b+min(18,(e-b)/2)
            seg=visible.intersection(LineString([(0,y),(2444,y)]))
            if seg.geom_type=='MultiLineString':seg=max(seg.geoms,key=lambda g:g.length)
            lo,_,hi,_=seg.bounds;x=(lo+hi)/2 if hi-lo<60 else lo+28;lab=sid[1:]
        xx,yy=(x-x0)*scale,(y-y0)*scale
        draw.rounded_rectangle((xx-27,yy-18,xx+27,yy+18),radius=5,fill='white',outline=col,width=2)
        draw.text((xx,yy),lab,font=font(26),anchor='mm',fill=col)
    crop.save(path)
    return crop

